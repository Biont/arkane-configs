#!/usr/bin/env bash
# Re-sync arkdep-build.d/depends/arkanelinux-generic verbatim from upstream.
#
# Never edit the vendored directory by hand, it is replaced wholesale on every sync.
# Put customizations in the biont variant instead, see scripts/check.sh for the rules.
#
# Usage: scripts/sync-upstream.sh [ref]   (default: main)
set -euo pipefail

UPSTREAM_REPO="https://github.com/arkanelinux/arkdep.git"
UPSTREAM_PATH="arkdep-build.d/depends/arkanelinux-generic"
REF="${1:-main}"

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
target="$repo_root/arkdep-build.d/depends/arkanelinux-generic"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

git clone --quiet --filter=blob:none --no-checkout "$UPSTREAM_REPO" "$tmp/arkdep"
git -C "$tmp/arkdep" sparse-checkout set --no-cone "/$UPSTREAM_PATH/"
git -C "$tmp/arkdep" checkout --quiet "$REF"

commit=$(git -C "$tmp/arkdep" rev-parse HEAD)
subject=$(git -C "$tmp/arkdep" log -1 --format='%ad %s' --date=short -- "$UPSTREAM_PATH")

rm -rf "$target"
cp -a "$tmp/arkdep/$UPSTREAM_PATH" "$target"

cat > "$target/UPSTREAM" <<EOF
# Generated by scripts/sync-upstream.sh, do not edit this directory by hand.
repo=$UPSTREAM_REPO
path=$UPSTREAM_PATH
commit=$commit
EOF

echo "Synced $UPSTREAM_PATH @ ${commit:0:12}"
echo "Last upstream change: $subject"
